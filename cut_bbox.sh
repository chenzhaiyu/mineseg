# Path to the root directory containing JP2 files and subfolders
root_dir="./dl_ds"

# Find all JP2 files recursively
jp2_files=$(find "$root_dir" -type f -name "*TCI.jp2")

for file in $jp2_files; do
    output_prefix="ROI_$(basename "$file" .jp2)"

    for bbox in "${bounding_boxes[@]}"; do
        gdal_translate -projwin $bbox "$file" "${output_prefix}_$(echo $bbox | tr -s ' ' '_').jp2"
    done
done